import assert from 'node:assert/strict';
import { BoxGeometry, Box3, Quaternion, Ray, Vector2, Vector3 } from 'three';
import { Mini } from '../src/mini.ts';
import { MiniDrag } from '../src/mini-drag.ts';
const mini=new Mini('test','Cube',{name:'Cube',geometry:new BoxGeometry(10,10,10).toNonIndexed().translate(0,0,5)});
const neighbor=new Mini('neighbor','Neighbor',{name:'Neighbor',geometry:new BoxGeometry(10,10,10).toNonIndexed().translate(20,0,5)});
const cached={summary:{plateZ:-1},output:new Uint8Array()};
mini.applyResult(cached,mini.revision);neighbor.applyResult(cached,neighbor.revision);
const ray=(x,y)=>new Ray(new Vector3(x,y,100),new Vector3(0,0,-1));
const drag=new MiniDrag(mini,'translate',new Vector2(100,100),new Vector3(0,0,11),new Quaternion(),null);
assert.equal(drag.update(new Vector2(101,101),ray(.1,.1)),false,'A click must not edit or clear supports');
assert.equal(mini.result,cached);
assert(drag.update(new Vector2(120,130),ray(12,8)));
assert.deepEqual(mini.coordinates(),[12,8,0]);assert.deepEqual(mini.exportSupportOffset(),[12,8,0]);
assert(drag.update(new Vector2(125,140),ray(15,10)));
drag.finish();
assert.deepEqual(mini.coordinates(),[15,10,0]);assert.deepEqual(mini.exportSupportOffset(),[15,10,0]);
assert.equal(mini.result,cached,'Body movement keeps cached supports');
assert.deepEqual(neighbor.coordinates(),[20,0,0]);assert.equal(neighbor.result,cached);
const rotate=new MiniDrag(mini,'rotate',new Vector2(100,100),new Vector3(15,10,11),new Quaternion(),Math.PI/12);
assert.equal(rotate.update(new Vector2(101,100),ray(15,10)),false);assert.equal(mini.result,cached);
assert(rotate.update(new Vector2(150,100),ray(15,10)));rotate.finish();
assert(Math.abs(mini.model.quaternion.angleTo(new Quaternion())-Math.PI/6)<1e-6,'Free rotation honors 15° snapping');
assert.equal(mini.result,undefined);assert.equal(neighbor.result,cached,'Body rotation only clears the rotated mini');
assert(Math.abs(new Box3().setFromObject(mini.model,true).min.z)<1e-6,'Rotated model rests on its original bed height');
const back=new MiniDrag(mini,'rotate',new Vector2(0,0),new Vector3(15,10,11),new Quaternion(),null);
const original=mini.model.quaternion.clone();back.update(new Vector2(30,20),ray(15,10));back.update(new Vector2(0,0),ray(15,10));back.finish();
assert(mini.model.quaternion.angleTo(original)<1e-6,'Dragging back to the starting point restores the orientation');
mini.dispose();neighbor.dispose();
console.log('PASS body drag translation, retained supports, click threshold, snapped rotation, grounding, and unaffected neighbor');
